#!/usr/bin/env python3
"""Build the single-file VGA Playground simulation of the Tiny Tapestation.

The VGA Playground (https://vga-playground.com) simulates one Verilog file whose top
module is called tt_um_vga_example. This script concatenates exactly the RTL that Tiny
Tapeout builds, in the order info.yaml lists it, and renames the top module:

    python3 scripts/buildsim.py                      # -> simulation/VGA_playground.v
    python3 scripts/buildsim.py -o other/path.v      # somewhere else

The file list and the top module both come from info.yaml (project.source_files and
project.top_module), so the simulation can never drift from the chip's sources.
"""

from __future__ import annotations

import argparse
import datetime
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PLAYGROUND_TOP = "tt_um_vga_example"


def git_describe() -> str:
    try:
        return subprocess.run(["git", "describe", "--always", "--dirty", "--tags"],
                              cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--output", type=Path, default=ROOT / "simulation" / "VGA_playground.v",
                    help="output file (default: simulation/VGA_playground.v)")
    ap.add_argument("--info", type=Path, default=ROOT / "info.yaml", help="the project's info.yaml")
    args = ap.parse_args()

    project = yaml.safe_load(args.info.read_text())["project"]
    top = project["top_module"]
    sources = [ROOT / "src" / f for f in project["source_files"]]
    missing = [s for s in sources if not s.exists()]
    if missing:
        print("ERROR: info.yaml lists missing files: " + ", ".join(map(str, missing)), file=sys.stderr)
        return 1

    top_decl = re.compile(rf"\bmodule\s+{re.escape(top)}\b")
    renamed = 0
    out = [
        "// Tiny Tapestation: single-file build for the VGA Playground (https://vga-playground.com)",
        f"// Generated by scripts/buildsim.py from info.yaml at {git_describe()} on "
        f"{datetime.datetime.now(datetime.timezone.utc):%Y-%m-%d %H:%M} UTC. Do not edit:",
        f"// edit src/ and rebuild. Top module {top} renamed to {PLAYGROUND_TOP}.",
        "",
    ]
    for src in sources:
        text = src.read_text()
        text, n = top_decl.subn(f"module {PLAYGROUND_TOP}", text)
        renamed += n
        out += [f"// {'=' * 76}", f"// src/{src.name}", f"// {'=' * 76}", text.rstrip(), ""]

    if renamed != 1:
        print(f"ERROR: expected exactly one 'module {top}' in the sources, found {renamed}", file=sys.stderr)
        return 1

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(out) + "\n")
    print(f"BUILD: {len(sources)} files from info.yaml -> {args.output.relative_to(ROOT) if args.output.is_relative_to(ROOT) else args.output}")
    print(f"BUILD: top module {top} -> {PLAYGROUND_TOP}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
